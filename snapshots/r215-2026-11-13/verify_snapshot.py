def integer_sum(node):
    if isinstance(node,ast.Expression):return integer_sum(node.body)
    if isinstance(node,ast.Constant) and type(node.value) is int:return node.value
    if isinstance(node,ast.BinOp) and isinstance(node.op,(ast.Add,ast.Sub)):
        a,b=integer_sum(node.left),integer_sum(node.right)
        return a+b if isinstance(node.op,ast.Add) else a-b
    raise ValueError('Only integer addition and subtraction are permitted')
